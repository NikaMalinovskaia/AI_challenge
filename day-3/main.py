import os
import google.generativeai as genai

# Инициализация API ключа
api_key = os.environ.get("GEMINI_API_KEY")
if not api_key:
    raise ValueError("Пожалуйста, установите переменную окружения GEMINI_API_KEY")

genai.configure(api_key=api_key)

# Выбираем модель
model = genai.GenerativeModel("gemini-2.5-flash")

task = (
    "Крестьянину нужно перевезти через реку волка, козу и капусту. У него есть лодка, "
    "в которую помещается только крестьянин, а с ним только один предмет (волк, коза или капуста). "
    "Волк ест козу, коза ест капусту, если оставить их без присмотра. Как перевезти всех?"
)

# 4 стратегии промптинга из задания
prompts = {
    "1_direct": task,
    
    "2_step_by_step": task + " Решай строго пошагово, описывая каждое действие.",
    
    "3_meta_prompt": (
        "Сначала составь максимально эффективный системный промпт для решения логической "
        "задачи о переправе, а затем примени его к следующей задаче: " + task
    ),
    
    "4_expert_panel": (
        "Рассмотри задачу с позиций трех экспертов: Логик (проверяет правила безопасности), "
        "Логистик (планирует оптимизацию рейсов) и Критик (ищет ошибки в плане). "
        "Каждый высказывает мнение, после чего выносится итоговое решение. Задача: " + task
    ),
}

# Последовательный запуск и вывод результатов
for name, prompt_text in prompts.items():
    print(f"=== Стратегия: {name} ===\n")
    try:
        response = model.generate_content(prompt_text)
        print(response.text)
    except Exception as e:
        print(f"Ошибка: {e}")
    print("\n" + "="*50 + "\n")
